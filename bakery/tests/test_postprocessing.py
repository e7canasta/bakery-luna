class TestPostprocessingIntegration:
    """
    Feature: End-to-end postprocessing

    Integration tests validating complete flows.
    """

    def test_segmentation_pipeline_deterministic(self):
        """
        Scenario: Same input produces same output
            Given the same model outputs
            When I postprocess twice
            Then results should be identical
        """
        # Given
        np.random.seed(42)
        output_boxes = np.random.rand(1, 116, 100)
        output_masks = np.random.rand(1, 32, 80, 80)

        # Set some detections above threshold
        output_boxes[0, 4:6, :5] = 0.9  # High scores for first 5 anchors

        # When - Process twice
        result1 = postprocess_segmentation(
            output_boxes, output_masks, (640, 640), conf_threshold=0.5
        )
        result2 = postprocess_segmentation(
            output_boxes, output_masks, (640, 640), conf_threshold=0.5
        )

        # Then - Results should match
        boxes1, scores1, class_ids1, masks1 = result1
        boxes2, scores2, class_ids2, masks2 = result2

        assert len(boxes1) == len(boxes2)
        if len(boxes1) > 0:
            np.testing.assert_array_equal(boxes1, boxes2)
            np.testing.assert_array_equal(scores1, scores2)
            np.testing.assert_array_equal(class_ids1, class_ids2)

    def test_pose_pipeline_deterministic(self):
        """
        Scenario: Same input produces same output
            Given the same model outputs
            When I postprocess twice
            Then results should be identical
        """
        # Given
        np.random.seed(42)
        output_data = np.random.rand(1, 56, 100)
        output_data[0, 4, :5] = 0.9  # High scores for first 5

        # When
        result1 = postprocess_pose(output_data, (640, 640), conf_threshold=0.5)
        result2 = postprocess_pose(output_data, (640, 640), conf_threshold=0.5)

        # Then
        boxes1, scores1, class_ids1, keypoints1 = result1
        boxes2, scores2, class_ids2, keypoints2 = result2

        assert len(boxes1) == len(boxes2)
        if len(boxes1) > 0:
            np.testing.assert_array_equal(boxes1, boxes2)
            np.testing.assert_array_equal(scores1, scores2)


